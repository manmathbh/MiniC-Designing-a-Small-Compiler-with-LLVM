#include "minic/Lexer.h"
#include <stdexcept>
#include <unordered_map>

// ─────────────────────────────────────────────────────────────────────────────
// Lexer.cpp — Hand-written lexical analyser.
//
// DESIGN NOTES (for interview):
//
// 1. CHARACTER-AT-A-TIME SCAN
//    We maintain a single `pos_` cursor into the source string. Each call to
//    nextToken() advances the cursor until a complete token is formed. This is
//    O(n) in source length with no backtracking — the same strategy used by
//    Clang's lexer (clang/lib/Lex/Lexer.cpp).
//
// 2. KEYWORD DETECTION VIA HASH MAP
//    We lex any identifier-shaped token first, then look it up in a static
//    keyword table. This avoids a forest of if/else and makes adding new
//    keywords O(1) — just add one line to the table.
//    SIMPLIFICATION 🏷️: Clang uses a keyword table generated by tblgen and
//    stored in a perfect hash for zero-collision lookup. We use unordered_map.
//
// 3. PEEK BUFFER
//    peek() lexes one token, stores it in peeked_, and returns it without
//    advancing. nextToken() drains peeked_ first if it is set. This gives
//    the parser its required 1-token lookahead without changing the grammar.
//
// 4. COMMENTS
//    Only // line comments are supported. Block comments (/* */) are not —
//    flag this if asked in an interview.
// ─────────────────────────────────────────────────────────────────────────────

namespace minic {

// ── Keyword table ────────────────────────────────────────────────────────────
static const std::unordered_map<std::string, TokenKind> kKeywords = {
    {"int",    TokenKind::KW_INT},
    {"if",     TokenKind::KW_IF},
    {"else",   TokenKind::KW_ELSE},
    {"while",  TokenKind::KW_WHILE},
    {"return", TokenKind::KW_RETURN},
    {"print",  TokenKind::KW_PRINT},
};

// ── Constructor ───────────────────────────────────────────────────────────────
Lexer::Lexer(std::string src) : src_(std::move(src)) {}

// ── Public interface ─────────────────────────────────────────────────────────

Token Lexer::nextToken() {
    // Drain the peek buffer first if peek() was called earlier.
    if (peeked_.has_value()) {
        Token t = std::move(*peeked_);
        peeked_.reset();
        return t;
    }
    return scan();
}

Token Lexer::peek() {
    if (!peeked_.has_value()) {
        peeked_ = scan();
    }
    return *peeked_;
}

// ── Private: the real scanner ─────────────────────────────────────────────────

Token Lexer::scan() {
    skipWhitespaceAndComments();

    if (atEnd()) return makeToken(TokenKind::END_OF_FILE);

    char c = current();

    // ── Integer literal ──────────────────────────────────────────────────
    if (std::isdigit(static_cast<unsigned char>(c)))
        return lexNumber();

    // ── Identifier or keyword ────────────────────────────────────────────
    if (std::isalpha(static_cast<unsigned char>(c)) || c == '_')
        return lexIdentOrKeyword();

    // ── Operators and delimiters ─────────────────────────────────────────
    advance(); // consume the character we're about to classify

    switch (c) {
    case '+': return makeToken(TokenKind::PLUS);
    case '-': return makeToken(TokenKind::MINUS);
    case '*': return makeToken(TokenKind::STAR);
    case '/': return makeToken(TokenKind::SLASH);
    case '%': return makeToken(TokenKind::PERCENT);
    case '(': return makeToken(TokenKind::LPAREN);
    case ')': return makeToken(TokenKind::RPAREN);
    case '{': return makeToken(TokenKind::LBRACE);
    case '}': return makeToken(TokenKind::RBRACE);
    case ',': return makeToken(TokenKind::COMMA);
    case ';': return makeToken(TokenKind::SEMICOLON);

    // One-or-two character tokens: check the next char before deciding.
    case '=': return makeToken(matchChar('=') ? TokenKind::EQ_EQ   : TokenKind::EQ);
    case '!': return makeToken(matchChar('=') ? TokenKind::BANG_EQ  : TokenKind::BANG);
    case '<': return makeToken(matchChar('=') ? TokenKind::LT_EQ    : TokenKind::LT);
    case '>': return makeToken(matchChar('=') ? TokenKind::GT_EQ    : TokenKind::GT);
    case '&':
        if (matchChar('&')) return makeToken(TokenKind::AMP_AMP);
        return errorToken(c);
    case '|':
        if (matchChar('|')) return makeToken(TokenKind::PIPE_PIPE);
        return errorToken(c);

    default:
        return errorToken(c);
    }
}

// ── Helper: skip whitespace and // line comments ──────────────────────────────
void Lexer::skipWhitespaceAndComments() {
    while (!atEnd()) {
        char c = current();
        if (c == '\n') {
            ++line_;
            ++pos_;
        } else if (std::isspace(static_cast<unsigned char>(c))) {
            ++pos_;
        } else if (c == '/' && pos_ + 1 < src_.size() && src_[pos_ + 1] == '/') {
            // Line comment: skip until newline (don't consume the '\n' itself;
            // the next iteration of this loop will handle it and increment line_).
            while (!atEnd() && current() != '\n') ++pos_;
        } else {
            break;
        }
    }
}

// ── Helper: lex an integer literal ───────────────────────────────────────────
Token Lexer::lexNumber() {
    int startLine = line_;
    std::size_t start = pos_;
    while (!atEnd() && std::isdigit(static_cast<unsigned char>(current())))
        ++pos_;

    std::string numStr = src_.substr(start, pos_ - start);
    long long val = 0;
    try {
        val = std::stoll(numStr);
    } catch (...) {
        throw std::runtime_error("Integer literal too large on line " +
                                 std::to_string(startLine) + ": " + numStr);
    }
    Token t;
    t.kind  = TokenKind::INT_LIT;
    t.line  = startLine;
    t.value = val;
    return t;
}

// ── Helper: lex identifier or keyword ────────────────────────────────────────
Token Lexer::lexIdentOrKeyword() {
    int startLine = line_;
    std::size_t start = pos_;
    while (!atEnd() && (std::isalnum(static_cast<unsigned char>(current())) || current() == '_'))
        ++pos_;

    std::string word = src_.substr(start, pos_ - start);

    // Keyword lookup
    auto it = kKeywords.find(word);
    if (it != kKeywords.end()) {
        Token t;
        t.kind  = it->second;
        t.line  = startLine;
        t.value = std::monostate{};
        return t;
    }

    // Plain identifier
    Token t;
    t.kind  = TokenKind::IDENT;
    t.line  = startLine;
    t.value = std::move(word);
    return t;
}

// ── Tiny helpers ──────────────────────────────────────────────────────────────

bool  Lexer::atEnd()    const { return pos_ >= src_.size(); }
char  Lexer::current()  const { return src_[pos_]; }
char  Lexer::advance()  { return src_[pos_++]; }

// Consume the current character only if it equals `expected`.
bool Lexer::matchChar(char expected) {
    if (atEnd() || current() != expected) return false;
    ++pos_;
    return true;
}

// Build a simple (no-value) token at the current line.
Token Lexer::makeToken(TokenKind k) const {
    Token t;
    t.kind  = k;
    t.line  = line_;
    t.value = std::monostate{};
    return t;
}

Token Lexer::errorToken(char c) {
    throw std::runtime_error(std::string("Unexpected character '") + c +
                             "' on line " + std::to_string(line_));
}

} // namespace minic
